#!/usr/bin/env python3
"""Turns an 8x16 code page 437 font into core/vc_font.c: 256 glyphs, one byte per row, most
significant bit leftmost. It reads either a BDF font with CP437 encodings (like Spleen's
cp437/spleen-8x16-ibm-437.bdf) or a pixel-outline TrueType font with Unicode mappings (like
Px437_ToshibaSat_8x16.ttf from VileR's Ultimate Oldschool PC Font Pack; this needs Pillow).
The comment lines given after the font go into the file's header comment.

    python3 font2c.py Px437_ToshibaSat_8x16.ttf \\
        "ToshibaSat 8x16 (Px437_ToshibaSat_8x16.ttf), from The Ultimate Oldschool PC Font Pack" \\
        "(c) 2016-2020 VileR, https://int10h.org/oldschool-pc-fonts/ -- CC BY-SA 4.0" \\
        "-- see NOTICE.md." > ../core/vc_font.c
"""
import sys

# The characters of code page 437, including the symbols shown for 0x01-0x1F and 0x7F
LOW = ' ☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼'


def cp437(code):
    if code < 32:
        return LOW[code]
    if code == 0x7F:
        return '⌂'
    return bytes([code]).decode('cp437')


def read_bdf(path):
    height = 16
    glyphs = {}
    ascent = None
    lines = open(path, encoding='latin-1').read().splitlines()
    i = 0
    while i < len(lines):
        words = lines[i].split()
        if words and words[0] == 'FONTBOUNDINGBOX':
            height = int(words[2])
            ascent = int(words[2]) + int(words[4])  # rows above the baseline
        if words and words[0] == 'STARTCHAR':
            code = None
            bbx = None
            while not lines[i].startswith('BITMAP'):
                w = lines[i].split()
                if w[0] == 'ENCODING':
                    code = int(w[1])
                elif w[0] == 'BBX':
                    bbx = [int(v) for v in w[1:5]]
                i += 1
            i += 1
            rows = []
            while not lines[i].startswith('ENDCHAR'):
                rows.append(int(lines[i][:2], 16))
                i += 1
            if code is not None and 0 <= code < 256:
                w, h, xoff, yoff = bbx
                cell = [0] * height
                top = ascent - (h + yoff)  # the glyph's first row in the cell
                for r, bits in enumerate(rows):
                    if 0 <= top + r < height:
                        cell[top + r] = (bits >> xoff) & 0xFF
                glyphs[code] = cell
        i += 1
    return glyphs


def read_ttf(path):
    """Draws each glyph at 16 pixels, unsmoothed; a pixel-outline font lands exactly on the grid."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(path, 16)
    glyphs = {}
    for code in range(256):
        im = Image.new('1', (8, 16), 0)
        draw = ImageDraw.Draw(im)
        draw.fontmode = '1'
        draw.text((0, 0), cp437(code), font=font, fill=1)
        glyphs[code] = [sum(im.getpixel((x, y)) << (7 - x) for x in range(8)) for y in range(16)]
    return glyphs


def main(path, credits):
    glyphs = read_ttf(path) if path.lower().endswith('.ttf') else read_bdf(path)
    out = sys.stdout
    out.write('/* Generated by vidcard/tools/font2c.py from ' + '\n * '.join(credits) + ' */\n')
    out.write('#include "vc.h"\n\n')
    out.write('const uint8_t vc_font8x16[256 * 16] = {\n')
    for code in range(256):
        cell = glyphs.get(code, [0] * 16)
        out.write('    ' + ', '.join('0x%02X' % b for b in cell) + ', /* %d */\n' % code)
    out.write('};\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2:])
